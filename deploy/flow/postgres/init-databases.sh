#!/bin/sh
# Creates two logical databases with separate owners/users (platform & intel).
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<SQL
CREATE ROLE ${PLATFORM_DB_USER} LOGIN PASSWORD '${PLATFORM_DB_PASSWORD}';
CREATE DATABASE ${PLATFORM_DB_NAME} OWNER ${PLATFORM_DB_USER};
CREATE ROLE ${INTEL_DB_USER} LOGIN PASSWORD '${INTEL_DB_PASSWORD}';
CREATE DATABASE ${INTEL_DB_NAME} OWNER ${INTEL_DB_USER};
REVOKE ALL ON DATABASE ${PLATFORM_DB_NAME} FROM PUBLIC;
REVOKE ALL ON DATABASE ${INTEL_DB_NAME} FROM PUBLIC;
SQL
